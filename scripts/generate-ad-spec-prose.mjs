/**
 * Derives the ad builder's per-template prose from the spec document itself.
 *
 * WHY THIS EXISTS AT ALL: `AD_PACK` keeps the twenty angle NAMES verbatim and
 * drops every rationale paragraph around them. So the model is told T7's fourth
 * angle is "how long an answer takes" and never told the thing that makes the
 * template work — that it "offers a calculation rather than a claim, which is
 * why it can talk about income without triggering the gate". That paragraph is
 * the difference between an ad written from the spec and an ad written from a
 * bullet list, and it is why the same document pasted into claude.ai produces
 * better copy than this app does.
 *
 * WHY GENERATE RATHER THAN TRANSCRIBE: §65 records four errors that came from
 * paraphrasing this document — a disclosure value that would have been false on
 * a live ad among them. `generate-section-index.mjs` is the precedent.
 *
 * WHY GENERATE RATHER THAN READ AT RUNTIME: docs/ is not traced into the Vercel
 * serverless bundle, so a readFileSync at request time works locally and throws
 * ENOENT in production (§50.5).
 *
 * Usage: node scripts/generate-ad-spec-prose.mjs [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const SPEC = join(ROOT, "docs/landlord-ad-template-pack-v1.md");
const OUT = join(ROOT, "src/lib/ads/specProse.ts");

/**
 * Which spec template each of the four shipped ids is.
 *
 * ⚠️ THE ONLY HAND-MAINTAINED LINE IN THE FILE, and the generator fails loudly
 * rather than emitting an empty string for an id it cannot find — an empty
 * prose block is exactly the silent degradation this replaces.
 */
const TEMPLATES = [
  { id: "never-see-the-messages", n: 3 },
  { id: "rules-keep-changing", n: 6 },
  { id: "what-would-it-earn", n: 7 },
  { id: "years-properties-review", n: 8 },
];

/** The lines of `## Template N — …`, up to the next `## `. */
function section(md, n) {
  const lines = md.split("\n");
  const start = lines.findIndex((l) => new RegExp(`^## Template ${n} —`).test(l));
  if (start === -1) throw new Error(`the spec has no Template ${n}`);
  let end = start + 1;
  while (end < lines.length && !/^## /.test(lines[end])) end += 1;
  return lines.slice(start + 1, end);
}

/**
 * The paragraphs immediately under the heading, before the field table.
 *
 * ⚠️ THE RATIONALE, NOT THE WHOLE SECTION. "Static layout" and "Video" describe
 * artwork the model does not draw, and the field table restates inputs the
 * brief already carries — paying ~400 tokens a call to tell it twice. What is
 * missing from the pack and is worth every token is WHY the template works.
 */
function rationale(body) {
  const out = [];
  for (const line of body) {
    if (/^\| /.test(line) || /^### /.test(line)) break;
    out.push(line);
  }
  return out.join("\n").trim();
}

/** The `### Claims note` paragraphs, in the spec's own words. */
function claimsNote(body) {
  const start = body.findIndex((l) => /^### Claims note/.test(l));
  if (start === -1) return "";
  let end = start + 1;
  while (end < body.length && !/^#{2,3} /.test(body[end])) end += 1;
  return body.slice(start + 1, end).join("\n").trim();
}

/** Backslashes and backticks, so the emitted template literal is inert. */
const q = (s) => "`" + s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";

function render(md) {
  const blocks = TEMPLATES.map(({ id, n }) => {
    const body = section(md, n);
    const why = rationale(body);
    const claims = claimsNote(body);
    if (!why) throw new Error(`Template ${n} has no rationale paragraph`);
    const text = claims ? `${why}\n\nWhat this template must never do: ${claims}` : why;
    return `  ${JSON.stringify(id)}: ${q(text)},`;
  });

  return `// GENERATED BY scripts/generate-ad-spec-prose.mjs — DO NOT EDIT.
// Source: docs/landlord-ad-template-pack-v1.md (spec v1, 2026-09-20).
// Re-run: npm run gen:ads   ·   Checked by specProse.test.ts on every build.

/**
 * What the spec SAYS about each template, as opposed to what it lists.
 *
 * ⚠️ THIS GOES IN THE USER TURN, NOT IN \`AD_PACK\`, AND THAT IS A CACHING
 * DECISION RATHER THAN A TIDINESS ONE. The pack is the shared cached prefix
 * across all three call kinds and its measured floor is ~1,500 tokens against a
 * 1,024 minimum — under 50% headroom. Moving the four template descriptions out
 * to make room for four rationales risks dropping it under the threshold, where
 * the cache is SILENTLY IGNORED. ~400 uncached tokens on the copy call is a
 * fraction of a penny; a silently dead cache on every call is not.
 */
export const AD_SPEC_PROSE: Record<string, string> = {
${blocks.join("\n")}
};
`;
}

const md = readFileSync(SPEC, "utf8");
const next = render(md);

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== next) {
    console.error("specProse.ts is stale. Run: npm run gen:ads");
    process.exit(1);
  }
  console.log("specProse.ts is current.");
} else {
  writeFileSync(OUT, next);
  console.log(`wrote ${OUT}`);
}
