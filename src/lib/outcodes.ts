/**
 * Normalise free-typed input ("le67 8qn", "LE67", "le678qn") to its outcode,
 * or null when it does not resolve to a known one. A full UK postcode always
 * ends in digit-letter-letter; anything else is treated as already being an
 * outcode attempt.
 */
export function parseOutcode(input: string): string | null {
  const s = input.trim().toUpperCase().replace(/\s+/g, "");
  if (!s) return null;
  const candidates: string[] = [];
  if (/\d[A-Z]{2}$/.test(s) && s.length > 4) candidates.push(s.slice(0, -3));
  candidates.push(s);
  for (const c of candidates) {
    if (OUTCODE_CENTROIDS[c]) return c;
  }
  return null;
}

export function outcodeCentroid(outcode: string): LatLng | null {
  return OUTCODE_CENTROIDS[outcode.toUpperCase()] ?? null;
}
